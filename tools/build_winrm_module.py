#!/usr/bin/env python3
"""
Generate windows/NetboxDhcpReader/NetboxDhcpReader.psm1 (+ .psd1) from the plugin's own
PowerShell Universal endpoint script, netbox_windows_dhcp/psu/dhcp_api_endpoints.ps1.

Each READ (GET) endpoint body is copied verbatim into a function, so the JSON the WinRM
transport returns is produced by exactly the same PowerShell as the PSU transport. Write
endpoints are never copied. Re-run after merging upstream changes:

    python3 tools/build_winrm_module.py            # regenerate
    python3 tools/build_winrm_module.py --check    # exit 1 if the committed module is stale

The generator fails loudly if upstream adds, renames or removes a GET endpoint, or if a
GET body starts using a variable the generated function does not provide.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'netbox_windows_dhcp' / 'psu' / 'dhcp_api_endpoints.ps1'
CONSTANTS = ROOT / 'netbox_windows_dhcp' / 'constants.py'
OUT_DIR = ROOT / 'windows' / 'NetboxDhcpReader'
PSM1 = OUT_DIR / 'NetboxDhcpReader.psm1'
PSD1 = OUT_DIR / 'NetboxDhcpReader.psd1'

# GET route -> (function name, parameters it receives; same names as the PSU variables)
ROUTES = {
    '/api/dhcp/health': ('Get-NbDhcpHealth', []),
    '/api/dhcp/scopes': ('Get-NbDhcpScopes', ['active_only', 'include_router']),
    '/api/dhcp/scopes/:scope_id': ('Get-NbDhcpScope', ['scope_id']),
    '/api/dhcp/leases': ('Get-NbDhcpLeases', ['scope_id', 'format']),
    '/api/dhcp/reservations': ('Get-NbDhcpReservations', ['scope_id', 'format']),
    '/api/dhcp/failover': ('Get-NbDhcpFailover', []),
    '/api/dhcp/options': ('Get-NbDhcpOptions', []),
    '/api/dhcp/options/server': ('Get-NbDhcpServerOptions', []),
    '/api/dhcp/options/scope/:scope_id': ('Get-NbDhcpScopeOptions', ['scope_id']),
    '/api/dhcp/exclusions': ('Get-NbDhcpExclusions', ['scope_id']),
}
# GET routes deliberately not exposed (not used by the plugin's client).
SKIPPED = {'/api/dhcp/metrics'}
# Request variables PSU injects; a GET body using one we do not pass is an error.
REQUEST_VARS = {'scope_id', 'format', 'active_only', 'include_router', 'Body'}

ENDPOINT_RE = re.compile(
    r"New-PSUEndpoint -Url '(?P<url>[^']+)' -Method (?P<method>\w+) @_ep\w+ "
    r"-Endpoint \(\[scriptblock\]::Create\(\$H \+ \{\n(?P<body>.*?)\n\}\.ToString\(\)\)\)",
    re.S,
)
HELPERS_RE = re.compile(r"^\$H = @'\n(?P<h>.*?)\n'@$", re.S | re.M)


class BuildError(Exception):
    pass


def plugin_version():
    m = re.search(r"PSU_SCRIPT_VERSION = '([^']+)'", CONSTANTS.read_text())
    if not m:
        raise BuildError('PSU_SCRIPT_VERSION not found in constants.py')
    return m.group(1)


def parse(text):
    h = HELPERS_RE.search(text)
    if not h:
        raise BuildError("shared helper block ($H = @'...'@) not found")
    endpoints = [(m['url'], m['method'].upper(), m['body']) for m in ENDPOINT_RE.finditer(text)]
    declared = len(re.findall(r'^New-PSUEndpoint ', text, re.M))
    if len(endpoints) != declared:
        raise BuildError(f'parsed {len(endpoints)} of {declared} New-PSUEndpoint blocks; source format changed')
    return h['h'], endpoints


def check_routes(endpoints):
    gets = {url: body for url, method, body in endpoints if method == 'GET'}
    unknown = set(gets) - set(ROUTES) - SKIPPED
    missing = set(ROUTES) - set(gets)
    if unknown:
        raise BuildError(f'new GET endpoint(s) upstream, map or skip them: {sorted(unknown)}')
    if missing:
        raise BuildError(f'GET endpoint(s) gone upstream: {sorted(missing)}')
    for url, (func, params) in ROUTES.items():
        used = {v for v in REQUEST_VARS if re.search(r'\$' + v + r'\b', gets[url])}
        extra = used - set(params)
        if extra:
            raise BuildError(f'{url} uses request variable(s) {sorted(extra)} that {func} does not provide')
    return gets


def indent(text, n):
    pad = ' ' * n
    return '\n'.join(pad + line if line.strip() else '' for line in text.splitlines())


def render(helpers, gets, version):
    funcs = []
    for url, (func, params) in ROUTES.items():
        param_block = ', '.join(f'[string]${p}' for p in params)
        funcs.append(
            f"# GET {url}\n"
            f"function {func} {{\n"
            f"    [CmdletBinding()]\n"
            f"    param({param_block})\n"
            f"    Invoke-NbEndpoint -Endpoint {{\n"
            f"{indent(gets[url], 4)}\n"
            f"    }}\n"
            f"}}\n"
        )
    exported = ', '.join(f"'{f}'" for f, _ in ROUTES.values())
    return f"""\
# =============================================================================
# NetboxDhcpReader {version} - READ-ONLY DHCP functions for the netbox-windows-dhcp
# plugin's WinRM transport.
#
# GENERATED by tools/build_winrm_module.py from netbox_windows_dhcp/psu/dhcp_api_endpoints.ps1.
# DO NOT EDIT. Each Get-NbDhcp* body is the plugin's own GET endpoint, verbatim.
# Write endpoints are not included. Exposed to NetBox only through the JEA endpoint
# created by windows/Install-NetboxDhcpReader.ps1.
#
# Every function returns ONE JSON string:  {{"status": <http-like code>, "body": "<json>", "log": [...]}}
# =============================================================================

# ---- Shared helpers from the plugin (verbatim) -------------------------------
{helpers}

# ---- PowerShell Universal shims ---------------------------------------------
function New-PSUApiResponse {{
    param([int]$StatusCode = 200, $Body, [string]$ContentType)
    $script:NbStatus = $StatusCode
    if ($null -ne $Body) {{ $Body }}
}}

function Write-PSULog {{
    param([string]$Level, [string]$Feature, [string]$Message, [string]$Resource)
    if ($script:NbLog) {{ $script:NbLog.Add("[$Level] $Message") }}
}}

function Invoke-NbEndpoint {{
    param([scriptblock]$Endpoint)
    $script:NbStatus = 200
    $script:NbLog = New-Object 'System.Collections.Generic.List[string]'
    try {{
        $out = & $Endpoint
        $body = (@($out) | Where-Object {{ $null -ne $_ }} | ForEach-Object {{ [string]$_ }}) -join ''
    }}
    catch {{
        $script:NbStatus = 500
        $body = (@{{ error = $_.Exception.Message }} | ConvertTo-Json -Compress)
    }}
    $envelope = [ordered]@{{ status = $script:NbStatus; body = $body; log = @($script:NbLog) }}
    ConvertTo-Json -InputObject $envelope -Compress -Depth 3
}}

# ---- Read endpoints ----------------------------------------------------------
{chr(10).join(funcs)}
Export-ModuleMember -Function {exported}
"""


def render_manifest(version):
    exported = ",\n        ".join(f"'{f}'" for f, _ in ROUTES.values())
    return f"""\
# GENERATED by tools/build_winrm_module.py - DO NOT EDIT
@{{
    RootModule        = 'NetboxDhcpReader.psm1'
    ModuleVersion     = '{version}'
    GUID              = '5b0f3c3e-7c1e-4b8a-9a55-3d1f6c2e9b10'
    Author            = 'netbox-windows-dhcp WinRM transport'
    Description       = 'Read-only DHCP functions for the netbox-windows-dhcp NetBox plugin (JEA).'
    PowerShellVersion = '5.1'
    RequiredModules   = @()
    FunctionsToExport = @(
        {exported}
    )
    CmdletsToExport   = @()
    VariablesToExport = @()
    AliasesToExport   = @()
}}
"""


def build():
    helpers, endpoints = parse(SOURCE.read_text())
    gets = check_routes(endpoints)
    version = plugin_version()
    if f"$PSU_SCRIPT_VERSION = '{version}'" not in helpers:
        raise BuildError(f'PSU script version in dhcp_api_endpoints.ps1 does not match constants.py ({version})')
    return render(helpers, gets, version), render_manifest(version)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if the committed module is out of date')
    args = ap.parse_args()
    try:
        psm1, psd1 = build()
    except BuildError as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 2
    if args.check:
        stale = [p.name for p, c in ((PSM1, psm1), (PSD1, psd1)) if not p.exists() or p.read_text() != c]
        if stale:
            print(f'STALE: {", ".join(stale)}; run tools/build_winrm_module.py', file=sys.stderr)
            return 1
        print('NetboxDhcpReader module is up to date.')
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    PSM1.write_text(psm1, newline='\r\n')
    PSD1.write_text(psd1, newline='\r\n')
    print(f'Wrote {PSM1.relative_to(ROOT)} and {PSD1.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
